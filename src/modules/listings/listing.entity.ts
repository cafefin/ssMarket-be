import {
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
  type Relation,
  UpdateDateColumn,
  VirtualColumn,
} from 'typeorm';
import { Campaign } from '../campaigns/campaign.entity.js';
import { Category } from '../categories/category.entity.js';
import { User } from '../users/user.entity.js';
import { ListingImage } from './listing-image.entity.js';
import { ListingCombo } from './listing-combo.entity.js';
import {
  ListingCondition,
  ListingMode,
  ListingStatus,
} from './listings.constants.js';

// The search_vector column is generated by the database from search_text and
// is deliberately not mapped here.
@Entity('listings')
export class Listing {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @Column({ name: 'seller_id', type: 'uuid' })
  sellerId!: string;

  @ManyToOne(() => User)
  @JoinColumn({ name: 'seller_id' })
  seller!: Relation<User>;

  @Column({ name: 'category_id', type: 'smallint' })
  categoryId!: number;

  @ManyToOne(() => Category)
  @JoinColumn({ name: 'category_id' })
  category!: Relation<Category>;

  @Column({ type: 'varchar', length: 120 })
  title!: string;

  @Column({ type: 'text', default: '' })
  description!: string;

  @Column({ type: 'varchar', length: 16 })
  unit!: string;

  /** Integer VND. */
  @Column({ name: 'unit_price', type: 'integer' })
  unitPrice!: number;

  /**
   * The pre-order round this product belongs to; null for in-stock goods.
   * A pre-order listing always has one (CK_listings_mode_campaign).
   */
  @Column({ name: 'campaign_id', type: 'uuid', nullable: true })
  campaignId!: string | null;

  @ManyToOne(() => Campaign, (campaign) => campaign.items, {
    nullable: true,
    onDelete: 'CASCADE',
  })
  @JoinColumn({ name: 'campaign_id' })
  campaign!: Relation<Campaign> | null;

  /** Position among the products of its round; 0 for in-stock goods. */
  @Column({ name: 'sort_order', type: 'smallint', default: 0 })
  sortOrder!: number;

  /**
   * What is left to sell, for in-stock products; null for pre-orders, which
   * are unlimited. PostgreSQL numeric arrives as a string.
   */
  @Column({
    name: 'stock_quantity',
    type: 'numeric',
    precision: 10,
    scale: 3,
    nullable: true,
  })
  stockQuantity!: string | null;

  @Column({ type: 'enum', enum: ListingMode, enumName: 'listings_mode_enum' })
  mode!: ListingMode;

  @Column({
    type: 'enum',
    enum: ListingStatus,
    enumName: 'listings_status_enum',
    default: ListingStatus.Draft,
  })
  status!: ListingStatus;

  /**
   * Payment terms of an in-stock product. Null for a product of a round,
   * whose terms are the round's; read them through `paymentTermsOf`.
   */
  @Column({ name: 'accepts_prepaid_qr', type: 'boolean', nullable: true })
  acceptsPrepaidQr!: boolean | null;

  @Column({ name: 'accepts_pay_on_delivery', type: 'boolean', nullable: true })
  acceptsPayOnDelivery!: boolean | null;

  /** Second-hand condition; null for pre-orders, food and older listings. */
  @Column({
    type: 'enum',
    enum: ListingCondition,
    enumName: 'listings_condition_enum',
    nullable: true,
  })
  condition!: ListingCondition | null;

  /** The percentage of `condition`, kept in a column so lists can filter by it. */
  @Column({ name: 'condition_percent', type: 'smallint', nullable: true })
  conditionPercent!: number | null;

  @Column({ name: 'search_text', type: 'text', default: '' })
  searchText!: string;

  @Column({ name: 'published_at', type: 'timestamptz', nullable: true })
  publishedAt!: Date | null;

  @Column({ name: 'closed_at', type: 'timestamptz', nullable: true })
  closedAt!: Date | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;

  /** Orders on this listing that have not been cancelled. Read-only. */
  @VirtualColumn({
    type: 'int',
    query: (alias) =>
      `(SELECT COUNT(DISTINCT "o"."id")::int FROM "order_lines" "ol" JOIN "orders" "o" ON "o"."id" = "ol"."order_id" WHERE "ol"."listing_id" = ${alias}."id" AND "o"."fulfillment_status" <> 'cancelled')`,
  })
  orderCount!: number;

  @OneToMany(() => ListingCombo, (combo) => combo.listing)
  combos!: Relation<ListingCombo[]>;

  @OneToMany(() => ListingImage, (image) => image.listing)
  images!: Relation<ListingImage[]>;
}
