import {
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
  type Relation,
  UpdateDateColumn,
} from 'typeorm';
import { Category } from '../categories/category.entity.js';
import { Listing } from '../listings/listing.entity.js';
import { User } from '../users/user.entity.js';

export enum CampaignStatus {
  Draft = 'draft',
  Open = 'open',
  Closed = 'closed',
}

/**
 * A pre-order round: the terms its products share (deadline, delivery date,
 * payment methods, category). The products are rows of `listings`.
 *
 * The search_vector column is generated by the database from search_text and
 * is deliberately not mapped here.
 */
@Entity('campaigns')
export class Campaign {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @Column({ name: 'seller_id', type: 'uuid' })
  sellerId!: string;

  @ManyToOne(() => User)
  @JoinColumn({ name: 'seller_id' })
  seller!: Relation<User>;

  @Column({ name: 'category_id', type: 'smallint' })
  categoryId!: number;

  @ManyToOne(() => Category)
  @JoinColumn({ name: 'category_id' })
  category!: Relation<Category>;

  @Column({ type: 'varchar', length: 120 })
  title!: string;

  @Column({ type: 'text', default: '' })
  description!: string;

  @Column({ name: 'order_deadline', type: 'timestamptz' })
  orderDeadline!: Date;

  /** Calendar date, YYYY-MM-DD. */
  @Column({ name: 'delivery_date', type: 'date' })
  deliveryDate!: string;

  @Column({ name: 'accepts_prepaid_qr', type: 'boolean' })
  acceptsPrepaidQr!: boolean;

  @Column({ name: 'accepts_pay_on_delivery', type: 'boolean' })
  acceptsPayOnDelivery!: boolean;

  @Column({
    type: 'enum',
    enum: CampaignStatus,
    enumName: 'campaigns_status_enum',
    default: CampaignStatus.Draft,
  })
  status!: CampaignStatus;

  /** The earlier round this one was reopened from, if any. */
  @Column({ name: 'reopened_from_id', type: 'uuid', nullable: true })
  reopenedFromId!: string | null;

  @Column({ name: 'search_text', type: 'text', default: '' })
  searchText!: string;

  @Column({ name: 'published_at', type: 'timestamptz', nullable: true })
  publishedAt!: Date | null;

  @Column({ name: 'closed_at', type: 'timestamptz', nullable: true })
  closedAt!: Date | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;

  /** Its products, as listings. */
  @OneToMany(() => Listing, (listing) => listing.campaign)
  items!: Relation<Listing[]>;
}
